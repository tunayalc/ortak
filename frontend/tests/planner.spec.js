import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route('**/api/health', route => route.fulfill({ json: { ai_ready: true, ai_model: 'llama3:8b', google_configured: false } }))
  await page.goto('/')
  await page.getByRole('button', { name: 'Buluşma planı oluştur', exact: true }).click()
})

test('plan is independently usable; optional transfer does not launch paid search', async ({ page }, testInfo) => {
  const paid = []
  page.on('request', request => { if (/\/(scenarios|locations\/parse|candidates\/search|routes\/matrix)$/.test(request.url())) paid.push(request.url()) })
  await page.getByLabel('Plan şehri', { exact: true }).fill('İzmir')
  await page.getByLabel('Kaç kişisiniz?', { exact: true }).fill('4')
  await page.getByRole('combobox', { name: 'Bütçe tercihi', exact: true }).selectOption('low')
  await page.getByRole('button', { name: 'Plan öner', exact: true }).click()
  await expect(page.locator('.plan-card')).toHaveCount(3)
  await page.getByRole('button', { name: 'Planı incele', exact: true }).first().click()
  await expect(page.locator('.plan-steps:visible')).toHaveCount(1)
  expect(paid).toHaveLength(0)
  await page.getByRole('navigation', { name: 'ORTAK bölümleri' }).getByRole('button', { name: 'Mekân bul', exact: true }).click()
  await expect(page.getByLabel('Şehir', { exact: true })).toHaveValue('Ankara')
  await page.getByRole('button', { name: 'Buluşma planı', exact: true }).click()
  await expect(page.locator('.plan-card')).toHaveCount(3)
  await page.getByRole('button', { name: 'ORTAK’ta mekân bul', exact: true }).first().click()
  await page.getByRole('button', { name: 'Planda kal', exact: true }).click()
  await expect(page.locator('.plan-card')).toHaveCount(3)
  for (const dark of [false, true]) {
    const toggle = page.getByRole('button', { name: dark ? 'Koyu temaya geç' : 'Açık temaya geç', exact: true })
    if (await toggle.isVisible()) await toggle.click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`planner-${dark ? 'dark' : 'light'}.png`), fullPage: true })
  }
  await page.getByRole('button', { name: 'ORTAK’ta mekân bul', exact: true }).first().click()
  await page.getByRole('button', { name: 'Bilgileri aktar', exact: true }).click()
  await expect(page.getByLabel('Şehir', { exact: true })).toHaveValue('İzmir')
  await expect(page.getByLabel('Grup', { exact: true })).toHaveValue('4')
  const locations = page.getByLabel('Link veya koordinat', { exact: true })
  await expect(locations).toHaveCount(4)
  for (const field of await locations.all()) await expect(field).toHaveValue('')
  expect(paid).toHaveLength(0)
  await page.getByRole('button', { name: 'Buluşma planı', exact: true }).click()
  await expect(page.locator('.plan-card')).toHaveCount(3)
})

test('Llama interpretation is a preview, not an automatic setting change', async ({ page }) => {
  await page.route('**/api/plans/interpret', route => route.fulfill({ json: { source: 'ollama', model: 'llama3:8b', warnings: [],
    brief: { city: 'İstanbul', area: 'Kadıköy', group_size: 5, duration_minutes: 90, budget: 'low', environment: 'indoor', pace: 'relaxed', interests: ['conversation'] } } }))
  await page.getByLabel('Buluşmayı anlat', { exact: true }).fill('İstanbul Kadıköy, beş kişi sohbet edelim.')
  await page.getByRole('checkbox', { name: /Metnimin sunucudaki Llama/ }).check()
  await page.getByRole('button', { name: 'Anlattıklarımdan taslak çıkar' }).click()
  await expect(page.getByRole('heading', { name: 'Taslağı incele' })).toBeVisible()
  await expect(page.getByLabel('Plan şehri', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: 'Taslağı kullan', exact: true }).click()
  await expect(page.getByLabel('Plan şehri', { exact: true })).toHaveValue('İstanbul')
  await page.getByRole('button', { name: 'Plan öner', exact: true }).click()
  await expect(page.locator('.plan-card')).toHaveCount(1)
})

test('missing context and incompatible constraints do not fabricate plans', async ({ page }) => {
  await page.getByRole('button', { name: 'Plan öner', exact: true }).click()
  await expect(page.getByText('Hangi şehirde buluşacaksınız?')).toBeVisible()
  await page.getByLabel('Plan şehri', { exact: true }).fill('Ankara')
  await page.getByLabel('Kaç kişisiniz?', { exact: true }).fill('3')
  await page.getByRole('combobox', { name: 'Ortam', exact: true }).selectOption('outdoor')
  await page.getByRole('checkbox', { name: 'Çalışma', exact: true }).check()
  await page.getByRole('button', { name: 'Plan öner', exact: true }).click()
  await expect(page.getByText(/Bu süre, ortam ve ilgi alanıyla/)).toBeVisible()
  await expect(page.locator('.plan-card')).toHaveCount(0)
  await page.getByLabel('Plan şehri', { exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('İlçe veya semt (isteğe bağlı)')).toBeFocused()
})

test('model outage leaves manual planner usable', async ({ page }) => {
  await page.route('**/api/plans/interpret', route => route.fulfill({ status: 503, json: { detail: 'Llama bağlantısı kurulamadı.' } }))
  await page.getByLabel('Buluşmayı anlat', { exact: true }).fill('Ankara üç kişi buluşalım.')
  await page.getByRole('checkbox', { name: /Metnimin sunucudaki Llama/ }).check()
  await page.getByRole('button', { name: 'Anlattıklarımdan taslak çıkar' }).click()
  await expect(page.getByRole('alert')).toContainText('Llama bağlantısı kurulamadı.')
  await page.getByLabel('Plan şehri', { exact: true }).fill('Ankara')
  await page.getByLabel('Kaç kişisiniz?', { exact: true }).fill('3')
  await page.getByRole('button', { name: 'Plan öner', exact: true }).click()
  await expect(page.locator('.plan-card')).toHaveCount(3)
})
