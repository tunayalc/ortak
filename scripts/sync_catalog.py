"""Generate the web and mobile venue lists from backend/app/services/places_catalog.py.

Run `python scripts/sync_catalog.py` after editing the catalog; `--check` fails when stale.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.services.places_catalog import MAX_SELECTED, public_catalog  # noqa: E402

sys.path.insert(0, str(ROOT / "scripts"))
from consent_content import SECTIONS, VERSION  # noqa: E402

ITEMS = public_catalog()
HEADER = "// Generated by scripts/sync_catalog.py from the backend catalog. Do not edit by hand.\n"
FILES = {
    ROOT / "frontend/src/catalog.js": HEADER
    + f"export const categories = {json.dumps(ITEMS, ensure_ascii=False, indent=2)}\n"
    + f"export const MAX_CATEGORIES = {MAX_SELECTED}\n"
    + "export const categoryNames = Object.fromEntries(categories.map(item => [item.id, item.label]))\n"
    + "export const categoryIds = categories.map(item => item.id)\n",
    ROOT / "mobile/src/catalog.ts": HEADER
    + f"export const categories = {json.dumps(ITEMS, ensure_ascii=False, indent=2)} as const;\n"
    + f"export const MAX_CATEGORIES = {MAX_SELECTED};\n"
    + "export const categoryNames: Record<string, string> = Object.fromEntries(categories.map(item => [item.id, item.label]));\n"
    + "export const categoryIds: string[] = categories.map(item => item.id);\n",
    ROOT / "frontend/src/consent.js": HEADER
    + f"export const CONSENT_VERSION = {json.dumps(VERSION)}\n"
    + f"export const consentSections = {json.dumps(SECTIONS, ensure_ascii=False, indent=2)}\n",
    ROOT / "mobile/src/consent.ts": HEADER
    + f"export const CONSENT_VERSION = {json.dumps(VERSION)};\n"
    + f"export const consentSections: Array<{{ id: string; title: string; items: string[] }}> = {json.dumps(SECTIONS, ensure_ascii=False, indent=2)};\n",
}


def main() -> int:
    stale = [path for path, text in FILES.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    if "--check" in sys.argv:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}")
        return 1 if stale else 0
    for path, text in FILES.items():
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
